package Loops;

public class Matrix {

    // [ [1,2] [3,4] ]

    public static void main(String[] args) {

        // continue and break 
        // label for loop

        for(int i = 0; i < 2; i++){ // 0 , 1
            for(int j = 0; j < 2; j++){ // 0 [0 , 1] , 1 [0 , 1]
                System.out.println("I :" + i + " J : " + j);
            }
        }
        
    }
    
}
